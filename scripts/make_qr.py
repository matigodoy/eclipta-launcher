#!/usr/bin/env python3
"""Writes the About screen's QR codes as vector drawables. Generated here, never at runtime.
Needs segno (pip install segno). Usage: python3 scripts/make_qr.py"""
import os
import segno

ROOT = os.path.join(os.path.dirname(__file__), "..", "launcher", "app", "src", "main", "res", "drawable")
CODES = {
    "qr_portfolio": "https://www.matigodoy.com.ar/",
    "qr_github": "https://github.com/matigodoy/eclipta-launcher",
}
QUIET = 4
DP_PER_MODULE = 5  # module edges land on whole pixels at density 1


def main():
    for name, url in CODES.items():
        # Same version for both, so both codes are the same size on screen.
        qr = segno.make(url, error="m", version=4, boost_error=False)
        rows = list(qr.matrix)
        size = len(rows) + 2 * QUIET
        path = []
        for y, row in enumerate(rows):
            x = 0
            while x < len(row):
                if not row[x]:
                    x += 1
                    continue
                start = x
                while x < len(row) and row[x]:
                    x += 1
                path.append(f"M{start + QUIET},{y + QUIET}h{x - start}v1h-{x - start}z")
        with open(os.path.join(ROOT, name + ".xml"), "w", encoding="utf-8") as f:
            f.write('<?xml version="1.0" encoding="utf-8"?>\n')
            f.write(f"<!-- {url}. Generated by scripts/make_qr.py. Black on white in every theme, or phones can't read it. -->\n")
            f.write('<vector xmlns:android="http://schemas.android.com/apk/res/android" '
                    f'android:width="{size * DP_PER_MODULE}dp" android:height="{size * DP_PER_MODULE}dp" '
                    f'android:viewportWidth="{size}" android:viewportHeight="{size}">\n')
            f.write(f'    <path android:fillColor="#FFFFFFFF" android:pathData="M0,0h{size}v{size}h-{size}z" />\n')
            f.write(f'    <path android:fillColor="#FF000000" android:pathData="{"".join(path)}" />\n')
            f.write("</vector>\n")
        print(name, size, "modules", url)


if __name__ == "__main__":
    main()
